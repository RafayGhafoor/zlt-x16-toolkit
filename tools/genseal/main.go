// Command genseal regenerates internal/zlt/sealed_gen.go.
//
// It encrypts the sensitive literals with AES-256-GCM under a fresh random key
// and writes a Go file containing only base64 ciphertext plus the key. Two
// consecutive runs produce different output, so builds are not byte-comparable.
//
//	go run ./tools/genseal
package main

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"text/template"

	"github.com/RafayGhafoor/zlt-x16-toolkit/internal/seal"
)

// literals must match the variable names declared in internal/zlt/sealed.go.
var literals = map[string]string{
	"sealedCGIPath":      "/cgi-bin/http.cgi",
	"sealedTelnetTmpl":   "busybox telnetd -l /bin/sh -p %d",
	"sealedDefaultUser":  "admin",
	"sealedDefaultPass":  "admin",
	"sealedDmzHost":      "127.0.0.1",
	"sealedDefaultHost":  "192.168.3.1",
	"sealedNoAuthMarker": "NO_AUTH",
	"sealedSuperUser":    "superadmin",
}

const header = `// Code generated by tools/genseal. DO NOT EDIT.

package zlt

// sealedKey and the sealedRaw* constants are regenerated by "make seal".
// They are obfuscation only - the key is recoverable from the binary.

const sealedKey = "{{.Key}}"

const (
{{- range .Items}}
	{{.Name}} = "{{.Value}}"
{{- end}}
)
`

func main() {
	keyBytes := make([]byte, 32)
	if _, err := rand.Read(keyBytes); err != nil {
		fmt.Fprintf(os.Stderr, "genseal: random: %v\n", err)
		os.Exit(1)
	}
	key := hex.EncodeToString(keyBytes)

	type item struct{ Name, Value string }
	var names []string
	// deterministic order
	for _, n := range []string{
		"sealedCGIPath", "sealedTelnetTmpl", "sealedDefaultUser",
		"sealedDefaultPass", "sealedDmzHost", "sealedDefaultHost",
		"sealedNoAuthMarker", "sealedSuperUser",
	} {
		names = append(names, n)
	}
	var items []item
	for _, n := range names {
		plain, ok := literals[n]
		if !ok {
			continue
		}
		sealed, err := seal.Seal(plain, key)
		if err != nil {
			fmt.Fprintf(os.Stderr, "genseal: seal %s: %v\n", n, err)
			os.Exit(1)
		}
		items = append(items, item{Name: n, Value: sealed})
	}

	f, err := os.Create("internal/zlt/sealed_gen.go")
	if err != nil {
		fmt.Fprintf(os.Stderr, "genseal: create: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	t := template.Must(template.New("gen").Parse(header))
	if err := t.Execute(f, map[string]any{"Key": key, "Items": items}); err != nil {
		fmt.Fprintf(os.Stderr, "genseal: write: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("genseal: wrote internal/zlt/sealed_gen.go (%d literals, key %s...)\n",
		len(items), key[:8])
}
